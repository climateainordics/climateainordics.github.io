#!/usr/bin/env python3
"""Make card-sized copies of post images for the card grids.

Many posts have an `image_small` that is only ~150-300px wide (made for the
old small floating thumbnails), which looks blurry in the cards. This script
writes an 800px-wide WebP copy of each post's image to images/cards/ and lists
them in _data/card_images.yml, keyed by post path. _includes/home/card.html
uses that copy when there is one, and falls back to image_small/image otherwise.

Posts are not modified. Re-run after adding posts (existing copies are skipped):

    pip install pillow pyyaml
    python3 _scripts/make_card_images.py
"""
import os
import re
import sys

import yaml
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH = 800        # cards are at most ~400px wide; 800px stays sharp on retina screens
QUALITY = 80
MIN_SMALL = 700    # use image_small only if it is at least this wide, else the full image
CATEGORIES = ["news", "events", "featured-works", "featured-member",
              "job-openings", "newsletter", "external"]


def front_matter(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"---\s*\n(.*?)\n---", text, re.S)
    if not m:
        return {}
    try:
        return yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        return {}


def local(src):
    """Repo path for a site image path, or None if it is remote or missing."""
    if not src or not isinstance(src, str) or src.startswith(("http:", "https:", "//")):
        return None
    p = os.path.join(ROOT, src.strip().lstrip("/"))
    return p if os.path.isfile(p) else None


def width(path):
    try:
        with Image.open(path) as im:
            return im.width
    except Exception:
        return 0


def main():
    mapping = {}
    made = 0
    for cat in CATEGORIES:
        d = os.path.join(ROOT, cat, "_posts")
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not name.endswith((".md", ".html")):
                continue
            fm = front_matter(os.path.join(d, name))
            small, full = local(fm.get("image_small")), local(fm.get("image"))
            if small and (width(small) >= MIN_SMALL or not full):
                src = small
            else:
                src = full or small
            if not src:
                continue
            rel = os.path.relpath(src, ROOT)
            if rel.startswith("images" + os.sep):
                rel = rel[len("images" + os.sep):]
            out_rel = os.path.join("images", "cards", os.path.splitext(rel)[0] + ".webp")
            out = os.path.join(ROOT, out_rel)
            if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(src):
                os.makedirs(os.path.dirname(out), exist_ok=True)
                try:
                    with Image.open(src) as im:
                        im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
                        if im.width > WIDTH:
                            im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
                        im.save(out, "WEBP", quality=QUALITY, method=6)
                    made += 1
                except Exception as e:
                    print(f"skip {src}: {e}", file=sys.stderr)
                    continue
            mapping[f"{cat}/_posts/{name}"] = "/" + out_rel.replace(os.sep, "/")

    with open(os.path.join(ROOT, "_data", "card_images.yml"), "w", encoding="utf-8") as f:
        f.write("# Generated by _scripts/make_card_images.py. Do not edit by hand.\n")
        for k in sorted(mapping):
            f.write(f'"{k}": "{mapping[k]}"\n')
    print(f"{len(mapping)} posts mapped, {made} images written")


if __name__ == "__main__":
    main()
